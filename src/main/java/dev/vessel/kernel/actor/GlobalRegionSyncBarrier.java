package dev.vessel.kernel.actor;

import java.util.Objects;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;
import java.util.concurrent.atomic.AtomicLong;
import java.util.function.Supplier;

/**
 * Universal Harmonizer Request-Reply Barrier for cross-region actor synchronization.
 * <p>
 * Enforces Architectural Decision 40 (Choice 2):
 * Allows legacy single-threaded Bukkit plugins operating on {@link GlobalRegionActorStrand} to
 * safely query state owned by a {@link RegionalActorStrand} via an asynchronous Request-Reply
 * barrier with a bounded 25ms timeout, preventing {@code IllegalStateException} crashes while
 * maintaining region state integrity.
 * </p>
 *
 * @version 1.0.2
 * @since 1.0.0 (Pass K-4)
 */
public class GlobalRegionSyncBarrier {

    /**
     * Default timeout for barrier cross-region ask pattern (25ms = one server tick budget).
     */
    public static final long DEFAULT_TIMEOUT_MILLIS = 25L;

    private final AtomicLong harmonizedCallCount = new AtomicLong(0);
    private final CrossRegionHarmonizerMetrics metrics = new CrossRegionHarmonizerMetrics();

    /**
     * Executes the supplier on the target strand. If already executing on the target strand,
     * the supplier is executed synchronously with zero overhead. Otherwise, an ask request is
     * dispatched and awaited with the default 25ms timeout.
     *
     * @param <T> result type
     * @param targetStrand the destination region strand owning the data
     * @param action the query or data supplier
     * @return the result generated by the target strand
     * @throws TimeoutException if the target strand does not reply within 25ms
     * @throws InterruptedException if the waiting thread is interrupted
     * @throws ExecutionException if the supplier throws an exception on the target strand
     */
    public <T> T executeWithBarrier(RegionalActorStrand targetStrand, Supplier<T> action)
            throws TimeoutException, InterruptedException, ExecutionException {
        return executeWithBarrier(targetStrand, action, DEFAULT_TIMEOUT_MILLIS, TimeUnit.MILLISECONDS);
    }

    /**
     * Executes the supplier on the target strand with a custom timeout.
     *
     * @param <T> result type
     * @param targetStrand destination regional strand
     * @param action query supplier
     * @param timeout duration to wait
     * @param unit time unit
     * @return result from target strand
     * @throws TimeoutException if timeout expires
     * @throws InterruptedException if interrupted
     * @throws ExecutionException if supplier fails
     */
    public <T> T executeWithBarrier(
            RegionalActorStrand targetStrand,
            Supplier<T> action,
            long timeout,
            TimeUnit unit
    ) throws TimeoutException, InterruptedException, ExecutionException {
        Objects.requireNonNull(targetStrand, "targetStrand cannot be null");
        Objects.requireNonNull(action, "action cannot be null");
        Objects.requireNonNull(unit, "unit cannot be null");

        // Zero-overhead fast path: already on target strand
        if (targetStrand.isCurrentStrand()) {
            return action.get();
        }

        harmonizedCallCount.incrementAndGet();
        long startNanos = System.nanoTime();
        CompletableFuture<T> future = targetStrand.ask(action);
        try {
            T result = future.get(timeout, unit);
            long elapsed = System.nanoTime() - startNanos;
            metrics.recordSuccess(elapsed);
            return result;
        } catch (TimeoutException e) {
            metrics.recordTimeout();
            throw e;
        }
    }

    /**
     * Returns total count of harmonized cross-strand barrier calls executed.
     *
     * @return harmonized call counter
     */
    public long getHarmonizedCallCount() {
        return harmonizedCallCount.get();
    }

    /**
     * Returns diagnostic metrics tracker for this barrier.
     *
     * @return metrics instance
     */
    public CrossRegionHarmonizerMetrics getMetrics() {
        return metrics;
    }
}
