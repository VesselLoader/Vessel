package dev.vessel.kernel.resourcepack.bedrock;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.NavigableMap;
import java.util.Objects;
import java.util.TreeMap;

/**
 * Generator transforming Java Edition language files ({@code assets/<namespace>/lang/*.json})
 * into standard Bedrock Edition localization files ({@code texts/*.lang}).
 * <p>
 * Eliminates unlocalized placeholder artifacts (such as {@code %tile.mod.block.name%}) by automatically
 * rewriting block identifiers to canonical Bedrock {@code tile.<namespace>.<id>.name} forms, and item identifiers
 * to {@code item.<namespace>.<id>.name} forms. Automatically provides fallback aliases for standard vanilla
 * namespace references, ensuring seamless cross-edition localization.
 * </p>
 * <p>
 * Strictly adheres to Rule 17 with zero inner, nested, or anonymous classes.
 * </p>
 *
 * @version 1.0.1
 * @author VESSEL Engine Team
 */
public final class VesselBedrockLanguageFileGenerator {

    private static final String HEADER_PREFIX = "## Auto-generated by VESSEL Bedrock Language Pipeline\n";

    /**
     * Constructs a new language file generator.
     */
    public VesselBedrockLanguageFileGenerator() {
    }

    /**
     * Converts a Java Edition JSON language string into formatted Bedrock {@code .lang} file content.
     *
     * @param defaultNamespace owning namespace when unqualified (e.g. "techmod", "minecraft")
     * @param jsonContent raw UTF-8 JSON text from Java pack
     * @return formatted Bedrock .lang text content
     */
    public String generateLangFromContent(String defaultNamespace, String jsonContent) {
        Objects.requireNonNull(defaultNamespace, "defaultNamespace cannot be null");
        Objects.requireNonNull(jsonContent, "jsonContent cannot be null");

        Map<String, String> javaMap = parseJsonToMap(jsonContent);
        return generateLangFromMap(defaultNamespace, javaMap);
    }

    /**
     * Converts a map of Java Edition translation key-value pairs into formatted Bedrock {@code .lang} content.
     *
     * @param defaultNamespace owning namespace when unqualified (e.g. "techmod", "minecraft")
     * @param javaTranslations map of Java translation key-value pairs
     * @return formatted Bedrock .lang text content
     */
    public String generateLangFromMap(String defaultNamespace, Map<String, String> javaTranslations) {
        Objects.requireNonNull(defaultNamespace, "defaultNamespace cannot be null");
        Objects.requireNonNull(javaTranslations, "javaTranslations cannot be null");

        Map<String, VesselBedrockLanguageEntry> entries = parseTranslations(defaultNamespace, javaTranslations);

        StringBuilder sb = new StringBuilder(entries.size() * 48);
        sb.append(HEADER_PREFIX);
        sb.append("## Namespace: ").append(defaultNamespace).append("\n\n");

        for (VesselBedrockLanguageEntry entry : entries.values()) {
            sb.append(entry.toLangLine()).append('\n');
        }

        return sb.toString();
    }

    /**
     * Parses a JSON language string into a sorted map of Bedrock language entries.
     *
     * @param defaultNamespace owning namespace
     * @param jsonContent raw JSON string
     * @return sorted map of Bedrock key to language entry
     */
    public NavigableMap<String, VesselBedrockLanguageEntry> parseTranslations(String defaultNamespace, String jsonContent) {
        Objects.requireNonNull(defaultNamespace, "defaultNamespace cannot be null");
        Objects.requireNonNull(jsonContent, "jsonContent cannot be null");

        Map<String, String> javaMap = parseJsonToMap(jsonContent);
        return parseTranslations(defaultNamespace, javaMap);
    }

    /**
     * Parses a map of Java key-values into a sorted map of Bedrock language entries.
     *
     * @param defaultNamespace owning namespace
     * @param javaTranslations map of Java translation key-value pairs
     * @return sorted map of Bedrock key to language entry
     */
    public NavigableMap<String, VesselBedrockLanguageEntry> parseTranslations(
            String defaultNamespace,
            Map<String, String> javaTranslations
    ) {
        Objects.requireNonNull(defaultNamespace, "defaultNamespace cannot be null");
        Objects.requireNonNull(javaTranslations, "javaTranslations cannot be null");

        String ns = defaultNamespace.trim().toLowerCase(java.util.Locale.ROOT);
        NavigableMap<String, VesselBedrockLanguageEntry> result = new TreeMap<>();

        for (Map.Entry<String, String> entry : javaTranslations.entrySet()) {
            String javaKey = entry.getKey();
            String value = entry.getValue();
            if (javaKey == null || value == null) {
                continue;
            }

            List<String> bedrockKeys = expandBedrockKeys(ns, javaKey);
            for (String bedrockKey : bedrockKeys) {
                result.put(bedrockKey, new VesselBedrockLanguageEntry(bedrockKey, value, ns));
            }
        }

        return result;
    }

    /**
     * Translates a single Java localization key into one or more Bedrock localization keys.
     * <p>
     * Applies the following transformations:
     * <ul>
     *   <li>{@code block.<ns>.<id>} &rarr; {@code tile.<ns>.<id>.name}, {@code tile.<ns>:<id>.name}, and item fallbacks</li>
     *   <li>{@code item.<ns>.<id>} &rarr; {@code item.<ns>.<id>.name} and {@code item.<ns>:<id>.name}</li>
     *   <li>{@code entity.<ns>.<id>} &rarr; {@code entity.<ns>.<id>.name} and {@code entity.<ns>:<id>.name}</li>
     *   <li>Unnamespaced {@code block.<id>} &rarr; namespaced {@code tile.<defaultNamespace>.<id>.name}</li>
     *   <li>Unnamespaced {@code item.<id>} &rarr; namespaced {@code item.<defaultNamespace>.<id>.name}</li>
     * </ul>
     * </p>
     *
     * @param defaultNamespace owning namespace when key is unqualified
     * @param javaKey input Java localization key
     * @return non-empty list of Bedrock localization keys
     */
    public List<String> expandBedrockKeys(String defaultNamespace, String javaKey) {
        Objects.requireNonNull(defaultNamespace, "defaultNamespace cannot be null");
        Objects.requireNonNull(javaKey, "javaKey cannot be null");

        String key = javaKey.trim();
        List<String> keys = new ArrayList<>(4);

        // Case 1: Java Block keys (e.g. block.minecraft.stone or block.techmod.crusher)
        if (key.startsWith("block.")) {
            String remainder = key.substring(6);
            String[] tokens = remainder.split("\\.", 2);
            if (tokens.length == 2) {
                String ns = tokens[0];
                String id = tokens[1];
                if (id.endsWith(".name")) {
                    id = id.substring(0, id.length() - 5);
                }
                keys.add("tile." + ns + "." + id + ".name");
                if (!ns.equalsIgnoreCase("minecraft")) {
                    keys.add("tile." + ns + ":" + id + ".name");
                    // Bedrock block held as an item in inventory
                    keys.add("item." + ns + "." + id + ".name");
                    keys.add("item." + ns + ":" + id + ".name");
                } else {
                    keys.add("tile." + id + ".name");
                    keys.add("item." + id + ".name");
                }
            } else if (tokens.length == 1) {
                String id = tokens[0];
                if (id.endsWith(".name")) {
                    id = id.substring(0, id.length() - 5);
                }
                if (defaultNamespace.equalsIgnoreCase("minecraft")) {
                    keys.add("tile.minecraft." + id + ".name");
                    keys.add("tile." + id + ".name");
                    keys.add("item.minecraft." + id + ".name");
                    keys.add("item." + id + ".name");
                } else {
                    keys.add("tile." + defaultNamespace + "." + id + ".name");
                    keys.add("tile." + defaultNamespace + ":" + id + ".name");
                    keys.add("item." + defaultNamespace + "." + id + ".name");
                    keys.add("item." + defaultNamespace + ":" + id + ".name");
                }
            }
            return keys;
        }

        // Case 2: Java Item keys (e.g. item.minecraft.apple or item.techmod.wrench)
        if (key.startsWith("item.")) {
            String remainder = key.substring(5);
            String[] tokens = remainder.split("\\.", 2);
            if (tokens.length == 2) {
                String ns = tokens[0];
                String id = tokens[1];
                if (id.endsWith(".name")) {
                    id = id.substring(0, id.length() - 5);
                }
                keys.add("item." + ns + "." + id + ".name");
                if (!ns.equalsIgnoreCase("minecraft")) {
                    keys.add("item." + ns + ":" + id + ".name");
                } else {
                    keys.add("item." + id + ".name");
                }
            } else if (tokens.length == 1) {
                String id = tokens[0];
                if (id.endsWith(".name")) {
                    id = id.substring(0, id.length() - 5);
                }
                if (defaultNamespace.equalsIgnoreCase("minecraft")) {
                    keys.add("item.minecraft." + id + ".name");
                    keys.add("item." + id + ".name");
                } else {
                    keys.add("item." + defaultNamespace + "." + id + ".name");
                    keys.add("item." + defaultNamespace + ":" + id + ".name");
                }
            }
            return keys;
        }

        // Case 3: Java Entity keys (e.g. entity.minecraft.zombie or entity.mymod.goblin)
        if (key.startsWith("entity.")) {
            String remainder = key.substring(7);
            String[] tokens = remainder.split("\\.", 2);
            if (tokens.length == 2) {
                String ns = tokens[0];
                String id = tokens[1];
                if (id.endsWith(".name")) {
                    id = id.substring(0, id.length() - 5);
                }
                keys.add("entity." + ns + "." + id + ".name");
                if (!ns.equalsIgnoreCase("minecraft")) {
                    keys.add("entity." + ns + ":" + id + ".name");
                } else {
                    keys.add("entity." + id + ".name");
                }
            } else if (tokens.length == 1) {
                String id = tokens[0];
                if (id.endsWith(".name")) {
                    id = id.substring(0, id.length() - 5);
                }
                if (defaultNamespace.equalsIgnoreCase("minecraft")) {
                    keys.add("entity.minecraft." + id + ".name");
                    keys.add("entity." + id + ".name");
                } else {
                    keys.add("entity." + defaultNamespace + "." + id + ".name");
                    keys.add("entity." + defaultNamespace + ":" + id + ".name");
                }
            }
            return keys;
        }

        // Case 4: Pre-existing tile keys (tile.mod.block or tile.mod.block.name)
        if (key.startsWith("tile.")) {
            String base = key.endsWith(".name") ? key : key + ".name";
            keys.add(base);
            return keys;
        }

        // Default: retain exact key
        keys.add(key);
        return keys;
    }

    private static Map<String, String> parseJsonToMap(String jsonContent) {
        String content = jsonContent.trim();
        if (content.startsWith("\uFEFF")) {
            content = content.substring(1).trim();
        }

        JsonElement rootElement;
        try {
            rootElement = JsonParser.parseString(content);
        } catch (Exception e) {
            throw new IllegalArgumentException("Failed to parse language JSON content: " + e.getMessage(), e);
        }

        if (!rootElement.isJsonObject()) {
            throw new IllegalArgumentException("Root language JSON element must be an object");
        }

        JsonObject obj = rootElement.getAsJsonObject();
        Map<String, String> map = new java.util.LinkedHashMap<>(obj.size());
        for (Map.Entry<String, JsonElement> member : obj.entrySet()) {
            String key = member.getKey();
            if (key == null || key.startsWith("//") || key.equalsIgnoreCase("_comment") || key.startsWith("_comment.")) {
                continue;
            }
            if (member.getValue().isJsonPrimitive()) {
                map.put(key, member.getValue().getAsString());
            }
        }
        return map;
    }
}
