package dev.vessel.kernel.item.capability;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Deep NBT tag preserver safeguarding custom mod machine compounds (e.g. Mekanism energy,
 * Botania mana, Applied Energistics storage cells) against Bukkit {@code ItemMeta} rewrites
 * under Decision 55 and CBT-0401..0800.
 *
 * <p>When a Bukkit plugin updates display lore, custom name, or enchantments, this preserver
 * ensures all non-Bukkit root NBT tags are extracted and merged back losslessly.</p>
 *
 * <p>Strictly adheres to Rule 17 with zero inner or nested classes.</p>
 *
 * @author VESSEL Engine Team
 * @version 1.0.0
 */
public final class CraftItemStackTagPreserver {

    private static final Logger LOGGER = LoggerFactory.getLogger(CraftItemStackTagPreserver.class);

    private static final Set<String> BUKKIT_MANAGED_KEYS = Set.of(
            "display",
            "Enchantments",
            "Damage",
            "RepairCost",
            "CustomModelData",
            "AttributeModifiers",
            "PublicBukkitValues",
            "Unbreakable",
            "CanDestroy",
            "CanPlaceOn",
            "BlockEntityTag",
            "trim",
            "potion_contents",
            "custom_name",
            "lore"
    );

    /**
     * Constructs a new tag preserver.
     */
    public CraftItemStackTagPreserver() {
    }

    /**
     * Checks if a specific root tag key is managed directly by Bukkit {@code ItemMeta}.
     *
     * @param key NBT compound key to evaluate
     * @return {@code true} if key is owned by standard Bukkit meta handlers
     */
    public boolean isBukkitManagedKey(String key) {
        if (key == null) {
            return false;
        }
        return BUKKIT_MANAGED_KEYS.contains(key);
    }

    /**
     * Extracts only mod-specific NBT compounds from an existing tag map.
     *
     * @param tags full original item tag map
     * @return unmodifiable map of mod-specific entries
     */
    public Map<String, Object> extractModTags(Map<String, Object> tags) {
        if (tags == null || tags.isEmpty()) {
            return Collections.emptyMap();
        }

        Map<String, Object> modTags = new LinkedHashMap<>();
        for (Map.Entry<String, Object> entry : tags.entrySet()) {
            String key = entry.getKey();
            if (!isBukkitManagedKey(key)) {
                modTags.put(key, entry.getValue());
            }
        }
        return Collections.unmodifiableMap(modTags);
    }

    /**
     * Merges Bukkit mutated tags with the original mod NBT data, ensuring zero loss of
     * complex mod machine states.
     *
     * @param originalTags      item's complete tag map prior to Bukkit mutation
     * @param bukkitMutatedTags tag map generated by Bukkit's {@code setItemMeta}
     * @return merged unmodifiable tag map with mod data preserved
     */
    public Map<String, Object> preserveModTags(
            Map<String, Object> originalTags,
            Map<String, Object> bukkitMutatedTags
    ) {
        Objects.requireNonNull(originalTags, "originalTags cannot be null");
        Objects.requireNonNull(bukkitMutatedTags, "bukkitMutatedTags cannot be null");

        Map<String, Object> merged = new LinkedHashMap<>(bukkitMutatedTags);
        Map<String, Object> modTags = extractModTags(originalTags);

        for (Map.Entry<String, Object> entry : modTags.entrySet()) {
            merged.put(entry.getKey(), entry.getValue());
        }

        LOGGER.debug("Preserved {} mod NBT tag branches during Bukkit meta merge", modTags.size());
        return Collections.unmodifiableMap(merged);
    }
}
