package dev.vessel.bootstrap.ecosystem;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Objects;

/**
 * Configures and manages the built-in GeyserMC Bedrock Edition RakNet UDP bridge
 * ({@code UDP 0.0.0.0:19132 -> TCP 127.0.0.1:25565}) backed by the auto-downloaded official
 * {@code Geyser-Standalone.jar} in {@code cache/ecosystem/}.
 *
 * <p>Strictly adheres to Rule 17 with zero inner, nested, or anonymous classes.</p>
 *
 * @version 1.0.0
 */
public final class BuiltInGeyserBedrockBridgeService {

    public static final int DEFAULT_BEDROCK_UDP_PORT = 19132;

    private volatile Process activeGeyserProcess;
    private volatile int activeBedrockUdpPort = DEFAULT_BEDROCK_UDP_PORT;
    private volatile int activeJavaTargetPort = 25565;

    /**
     * Scaffolds Geyser's {@code config.yml} inside {@code serverRoot/cache/ecosystem/geyser-runtime/}
     * so Bedrock Edition clients can connect on UDP port {@code 19132} with Floodgate/offline
     * local authentication forwarding to the VESSEL Java server.
     *
     * @param serverRoot     server root directory
     * @param javaServerPort local Java server TCP port (e.g., {@code 25565})
     * @param bedrockUdpPort Bedrock RakNet UDP port (e.g., {@code 19132})
     * @return path to the generated {@code config.yml}
     */
    public Path scaffoldGeyserRuntimeConfig(Path serverRoot, int javaServerPort, int bedrockUdpPort) {
        Objects.requireNonNull(serverRoot, "serverRoot must not be null");
        this.activeJavaTargetPort = javaServerPort > 0 ? javaServerPort : 25565;
        this.activeBedrockUdpPort = bedrockUdpPort > 0 ? bedrockUdpPort : DEFAULT_BEDROCK_UDP_PORT;

        Path runtimeDir = serverRoot.resolve("cache").resolve("ecosystem").resolve("geyser-runtime");
        Path configPath = runtimeDir.resolve("config.yml");
        try {
            Files.createDirectories(runtimeDir);
            String configYaml = """
                    # -------------------------------------------------------------------------
                    # GeyserMC Configuration (Auto-Generated by VESSEL Sovereign Microkernel)
                    # -------------------------------------------------------------------------
                    bedrock:
                      address: 0.0.0.0
                      port: %d
                      clone-remote-port: false
                      motd1: "VESSEL Sovereign Server"
                      motd2: "Universal Java & Bedrock Crossplay"
                      server-name: "VESSEL"
                      compression-level: 6
                      enable-proxy-protocol: false
                    remote:
                      address: 127.0.0.1
                      port: %d
                      auth-type: offline
                      allow-password-authentication: true
                      use-proxy-protocol: false
                      forward-hostname: false
                    floodgate-key-file: key.pem
                    saved-user-logins: []
                    pending-authentication-timeout: 120
                    command-suggestions: true
                    passthrough-motd: true
                    passthrough-player-counts: true
                    legacy-ping-passthrough: false
                    ping-passthrough-interval: 3
                    forward-player-ping: true
                    max-players: 100
                    debug-mode: false
                    allow-third-party-capes: true
                    allow-third-party-ears: false
                    show-cooldown: title
                    show-coordinates: true
                    disable-bedrock-scaffolding: false
                    emote-offhand-workaround: "disabled"
                    cache-images: 0
                    allow-custom-skulls: true
                    max-visible-custom-skulls: 128
                    custom-skull-render-distance: 32
                    add-non-bedrock-items: true
                    above-bedrock-nether-building: true
                    force-resource-packs: true
                    xbox-achievements-enabled: false
                    log-player-ip-addresses: true
                    notify-on-new-bedrock-update: true
                    unusable-space-block: minecraft:barrier
                    metrics:
                      enabled: false
                      uuid: generateduuid
                    scoreboard-packet-threshold: 20
                    enable-proxy-connections: false
                    mtu: 1400
                    use-direct-connection: true
                    disable-compression: true
                    config-version: 4
                    """.stripIndent().formatted(this.activeBedrockUdpPort, this.activeJavaTargetPort);
            Files.writeString(configPath, configYaml, StandardCharsets.UTF_8);
            return configPath;
        } catch (IOException e) {
            throw new IllegalStateException("Failed to scaffold Geyser config.yml at " + configPath, e);
        }
    }

    /**
     * Starts the live Geyser Bedrock RakNet UDP bridge in the background if the official
     * {@code Geyser-Standalone.jar} binary is present in {@code cache/ecosystem/}.
     *
     * @param serverRoot     server root directory
     * @param javaServerPort local Java server TCP port (e.g., {@code 25565})
     * @param bedrockUdpPort Bedrock RakNet UDP port (e.g., {@code 19132})
     * @return {@code true} if the live Geyser Bedrock bridge process was started
     */
    public boolean startGeyserBridgeIfAvailable(Path serverRoot, int javaServerPort, int bedrockUdpPort) {
        Objects.requireNonNull(serverRoot, "serverRoot must not be null");
        scaffoldGeyserRuntimeConfig(serverRoot, javaServerPort, bedrockUdpPort);

        Path geyserStandaloneJar = serverRoot
                .resolve("cache")
                .resolve("ecosystem")
                .resolve("Geyser-Standalone.jar")
                .toAbsolutePath()
                .normalize();
        try {
            if (!Files.isRegularFile(geyserStandaloneJar) || Files.size(geyserStandaloneJar) < 4096L) {
                return false;
            }
            Path runtimeDir = serverRoot
                    .resolve("cache")
                    .resolve("ecosystem")
                    .resolve("geyser-runtime")
                    .toAbsolutePath()
                    .normalize();
            String javaBin = ProcessHandle.current().info().command().orElse("java");
            ProcessBuilder pb = new ProcessBuilder(
                    javaBin,
                    "-Xms256M",
                    "-Xmx512M",
                    "-Djava.net.preferIPv4Stack=true",
                    "-jar",
                    geyserStandaloneJar.toString(),
                    "--nogui");
            pb.directory(runtimeDir.toFile());
            pb.redirectErrorStream(true);
            pb.redirectOutput(runtimeDir.resolve("geyser-bridge.log").toFile());
            this.activeGeyserProcess = pb.start();
            Runtime.getRuntime().addShutdownHook(
                    new Thread(this::stopBedrockBridge, "vessel-geyser-shutdown-hook"));
            return this.activeGeyserProcess.isAlive();
        } catch (Exception ignored) {
            return false;
        }
    }

    /**
     * Forwards a Geyser command line (e.g., {@code "geyser list"}, {@code "geyser reload"}) to the
     * running Geyser bridge process's standard input if active.
     *
     * @param geyserCommand command string to forward
     * @return {@code true} if forwarded to a running Geyser process
     */
    public boolean dispatchCommandToBridgeProcess(String geyserCommand) {
        Process proc = this.activeGeyserProcess;
        if (proc == null || !proc.isAlive() || geyserCommand == null) {
            return false;
        }
        try {
            OutputStream stdin = proc.getOutputStream();
            stdin.write((geyserCommand.trim() + "\n").getBytes(StandardCharsets.UTF_8));
            stdin.flush();
            return true;
        } catch (IOException ignored) {
            return false;
        }
    }

    /**
     * Stops the active Geyser Bedrock bridge process if running.
     */
    public void stopBedrockBridge() {
        Process proc = this.activeGeyserProcess;
        if (proc != null && proc.isAlive()) {
            proc.destroy();
        }
    }

    /**
     * Returns whether the Geyser Bedrock UDP bridge process is currently alive.
     *
     * @return {@code true} if running
     */
    public boolean isBridgeRunning() {
        Process proc = this.activeGeyserProcess;
        return proc != null && proc.isAlive();
    }

    /**
     * Returns the configured Bedrock UDP port (default {@code 19132}).
     *
     * @return UDP port
     */
    public int getActiveBedrockUdpPort() {
        return activeBedrockUdpPort;
    }

    /**
     * Returns the configured target Java TCP port (default {@code 25565}).
     *
     * @return TCP port
     */
    public int getActiveJavaTargetPort() {
        return activeJavaTargetPort;
    }
}
