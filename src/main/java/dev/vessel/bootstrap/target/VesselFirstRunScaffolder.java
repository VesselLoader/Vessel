package dev.vessel.bootstrap.target;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Objects;

/**
 * Scaffolds the initial server directory structure and the {@code vessel-config/}
 * hierarchy (Decision 4) on first run.
 *
 * @version 1.0.0
 */
public final class VesselFirstRunScaffolder {

    private static final List<String> REQUIRED_VESSEL_CONFIG_FILES = List.of(
            "build.yml",
            "versions.yml",
            "first-run.yml",
            "filesystem.yml",
            "packs.yml",
            "ignore.yml",
            "geyser.yml",
            "identity.yml"
    );

    /**
     * Creates a new first-run directory scaffolder.
     */
    public VesselFirstRunScaffolder() {
    }

    /**
     * Scaffolds the canonical server directories ({@code mods/}, {@code plugins/},
     * {@code vessel-config/}, {@code vessel-config/defaults/forge/},
     * {@code vessel-config/overrides/}) and default files ({@code eula.txt},
     * {@code vessel.yml}, and all 8 {@code vessel-config/*.yml} files).
     *
     * @param serverRoot the root directory of the server
     */
    public void scaffoldServerDirectories(Path serverRoot) {
        Objects.requireNonNull(serverRoot, "serverRoot must not be null");
        try {
            Files.createDirectories(serverRoot.resolve("mods"));
            Files.createDirectories(serverRoot.resolve("plugins"));
            Path vesselConfigDir = serverRoot.resolve("vessel-config");
            Files.createDirectories(vesselConfigDir);
            Files.createDirectories(vesselConfigDir.resolve("defaults").resolve("forge"));
            Files.createDirectories(vesselConfigDir.resolve("defaults").resolve("neoforge"));
            Files.createDirectories(vesselConfigDir.resolve("defaults").resolve("fabric"));
            Files.createDirectories(vesselConfigDir.resolve("defaults").resolve("quilt"));
            Files.createDirectories(vesselConfigDir.resolve("defaults").resolve("bukkit"));
            Files.createDirectories(vesselConfigDir.resolve("overrides"));

            Path eulaFile = serverRoot.resolve("eula.txt");
            if (!Files.exists(eulaFile)) {
                Files.writeString(
                        eulaFile,
                        "# Generated by VESSEL First-Run Scaffolder\neula=false\n",
                        StandardCharsets.UTF_8);
            }

            VesselServerConfig serverConfig = new VesselServerConfig();
            serverConfig.loadOrGenerateDefaults(serverRoot);

            for (String configFileName : REQUIRED_VESSEL_CONFIG_FILES) {
                Path targetFile = vesselConfigDir.resolve(configFileName);
                if (!Files.exists(targetFile)) {
                    String header = "# VESSEL Configuration File: " + configFileName + "\nenabled: true\n";
                    Files.writeString(targetFile, header, StandardCharsets.UTF_8);
                }
            }
        } catch (IOException ex) {
            throw new IllegalStateException("Failed to scaffold server directories in " + serverRoot, ex);
        }
    }

    /**
     * Returns the immutable list of required configuration files under {@code vessel-config/}.
     *
     * @return list of 8 required YAML file names
     */
    public List<String> getRequiredVesselConfigFiles() {
        return REQUIRED_VESSEL_CONFIG_FILES;
    }
}
